import blueBlot from '@/assets/watercolor/blot-blue.webp';
import rainbowStrokeTorn from '@/assets/watercolor/stroke-rainbow.webp';
import bee from '@/assets/watercolor/bee.webp';
import butterflyPink from '@/assets/watercolor/butterfly-pink.webp';
import butterflyRainbow from '@/assets/watercolor/butterfly-rainbow.webp';
import bouquet from '@/assets/watercolor/bouquet.webp';
import dragonflyTeal from '@/assets/watercolor/dragonfly-teal.webp';
import dragonflyBlue from '@/assets/watercolor/dragonfly-blue.webp';
import dragonflyGreen from '@/assets/watercolor/dragonfly-green.webp';
import butterflyGreen from '@/assets/watercolor/butterfly-green.webp';
import butterflyBlue from '@/assets/watercolor/butterfly-blue.webp';
import butterflyYellow from '@/assets/watercolor/butterfly-yellow.webp';
import lavenderHeart from '@/assets/watercolor/lavender-heart.webp';

/**
 * Decorative watercolor pieces (2026-11, client: "strona ma wyrażać
 * radość"). The orange/blue blots, bee, butterflies, dragonflies, lavender heart and
 * forget-me-not bouquet are the client's own artwork (originals in plan/brand/client-art,
 * cut out with plan/brand/cutout-client-art.cjs); the backgrounds
 * and rainbow stroke are generated by plan/brand/paint-watercolor.cjs.
 *
 * WatercolorAccent — a loose blot for section corners. Put it inside a
 * section with `relative isolate overflow-hidden`: the blot sits at -z-10
 * (above the section background, below the content) and multiplies with
 * the background like real paint. Position/size it with `className`.
 *
 * WatercolorFriend — a little painted creature or bouquet (bee, butterflies,
 * flowers). Positioned by the caller; `float` makes it hover gently
 * (switched off for people who prefer reduced motion).
 *
 * RainbowStroke — a brush stroke flowing through the spiral colors, used
 * under page titles.
 */

const BLOTS = { warm: orangeBlot, cool: blueBlot } as const;

export type WatercolorTone = keyof typeof BLOTS;

interface WatercolorAccentProps {
  tone: WatercolorTone;
  className?: string;
}

export function WatercolorAccent({
  tone,
  className = '',
}: WatercolorAccentProps) {
  return (
    <img
      src={BLOTS[tone]}
      alt=""
      aria-hidden="true"
      loading="lazy"
      decoding="async"
      draggable={false}
      className={`pointer-events-none absolute -z-10 select-none mix-blend-multiply ${className}`}
    />
  );
}

const FRIENDS = {
  bee,
  butterfly: butterflyPink,
  wings: butterflyRainbow,
  bouquet,
  dragonfly: dragonflyTeal,
  dragonflyBlue,
  dragonflyGreen,
  butterflyGreen,
  butterflyBlue,
  butterflyYellow,
  lavender: lavenderHeart,
} as const;

export type WatercolorFriendKind = keyof typeof FRIENDS;

interface WatercolorFriendProps {
  kind: WatercolorFriendKind;
  className?: string;
  /** Gentle hovering in place. */
  float?: boolean;
  /**
   * Horizontal flight (bee, pink butterfly): flies ~1.6× its width towards
   * this side and back, turning around at each end. Overrides `float`.
   */
  fly?: 'left' | 'right';
  /** Animation delay in seconds, so several friends don't move in sync. */
  delay?: number;
}

const FLY_CLASS = {
  left: 'animate-fly-left',
  right: 'animate-fly-right',
} as const;

export function WatercolorFriend({
  kind,
  className = '',
  float = false,
  fly,
  delay = 0,
}: WatercolorFriendProps) {
  let animation = '';
  if (fly) animation = `${FLY_CLASS[fly]} motion-reduce:animate-none`;
  else if (float) animation = 'animate-float motion-reduce:animate-none';
  return (
    <img
      src={FRIENDS[kind]}
      alt=""
      aria-hidden="true"
      loading="lazy"
      decoding="async"
      draggable={false}
      style={animation && delay ? { animationDelay: `${delay}s` } : undefined}
      className={`pointer-events-none absolute h-auto select-none ${animation} ${className}`}
    />
  );
}

/**
 * Title underline: the watercolor brush stroke (client 2026-11-10 tried a
 * smooth line — assets/watercolor/stroke-rainbow-smooth.webp — and chose
 * to keep the brush stroke). Colours: coral → gold → turquoise → blue, no
 * violet / pink, so it doesn't read as a full-spectrum rainbow.
 */
const rainbowStroke = rainbowStrokeTorn;

export function RainbowStroke({ className = '' }: { className?: string }) {
  return (
    <img
      src={rainbowStroke}
      alt=""
      aria-hidden="true"
      decoding="async"
      draggable={false}
      className={`pointer-events-none block h-auto select-none ${className}`}
    />
  );
}
