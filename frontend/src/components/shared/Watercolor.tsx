/**
 * Decorative watercolor pieces (2026-11, client: "strona ma wyrażać
 * radość"). The orange/blue blots, bee, butterflies, dragonflies, lavender heart and
 * forget-me-not bouquet are the client's own artwork (originals in plan/brand/client-art,
 * cut out with plan/brand/cutout-client-art.cjs); the backgrounds
 * and rainbow stroke are generated by plan/brand/paint-watercolor.cjs.
 *
 * WatercolorAccent — a loose blot for section corners. Put it inside a
 * section with `relative isolate overflow-hidden`: the blot sits at -z-10
 * (above the section background, below the content) and multiplies with
 * the background like real paint. Position/size it with `className`.
 *
 * WatercolorFriend — a little painted creature or bouquet (bee, butterflies,
 * flowers). Positioned by the caller; `float` makes it hover gently
 * (switched off for people who prefer reduced motion).
 *
 * RainbowStroke — a brush stroke flowing through the spiral colors, used
 * under page titles.
 */

const BLOTS = { warm: orangeBlot, cool: blueBlot } as const;

export type WatercolorTone = keyof typeof BLOTS;

interface WatercolorAccentProps {
  tone: WatercolorTone;
  className?: string;
}

export function WatercolorAccent({
  tone,
  className = '',
}: WatercolorAccentProps) {
  return (
    <img
      src={BLOTS[tone]}
      alt=""
      aria-hidden="true"
      loading="lazy"
      decoding="async"
      draggable={false}
      className={`pointer-events-none absolute -z-10 select-none mix-blend-multiply ${className}`}
    />
  );
}

const FRIENDS = {
  bee,
  butterfly: butterflyPink,
  wings: butterflyRainbow,
  bouquet,
  dragonfly: dragonflyTeal,
  dragonflyBlue,
  dragonflyGreen,
  butterflyGreen,
  butterflyBlue,
  butterflyYellow,
  lavender: lavenderHeart,
} as const;

export type WatercolorFriendKind = keyof typeof FRIENDS;

interface WatercolorFriendProps {
  kind: WatercolorFriendKind;
  className?: string;
  /** Gentle hovering in place. */
  float?: boolean;
  /**
   * Horizontal flight (bee, pink butterfly): flies ~1.6× its width towards
   * this side and back, turning around at each end. Overrides `float`.
   */
  fly?: 'left' | 'right';
  /**
   * Flutters around its spot (left / right and up / down) without drifting
   * away — for butterflies centred above content. Overrides `float`.
   */
  flutter?: boolean;
  /** Animation delay in seconds, so several friends don't move in sync. */
  delay?: number;
}

/**
 * Flights become a gentle float for people who ask their device to reduce
 * motion (client 2026-11-10: on her phone nothing moved — phones in battery
 * saving / "remove animations" mode report prefers-reduced-motion), so the
 * page still feels alive without anything crossing the screen.
 */
const FLY_CLASS = {
  left: 'animate-fly-left motion-reduce:animate-float',
  right: 'animate-fly-right motion-reduce:animate-float',
} as const;

/**
 * Friends whose wings move (client 2026-11-10), drawn as stacked same-size
 * layers, bottom to top:
 * - butterflies — split along the body into left wings, right wings and
 *   the body by plan/brand/split-flapping-butterflies.cjs; the wings fold
 *   towards the body line (`hinge`, % of the width). `tilt` turns the
 *   upright cut-out back to the angle it was painted at.
 * - the bee — body + wings by plan/brand/split-bee-wings.cjs; the wings
 *   buzz around their roots.
 * - butterflies painted from the side (pink, green) — wings + body by
 *   plan/brand/split-side-butterflies.cjs; the wings beat towards the body.
 * `ratio` is height / width of the layers.
 */
interface FlapLayer {
  src: string;
  /** Animation class; none = the layer stays still. */
  animate?: string;
  /** transform-origin of the animated layer. */
  origin?: string;
}

function butterflyLayers(
  left: string,
  right: string,
  body: string,
  hinge: number,
): FlapLayer[] {
  const origin = `${hinge}% 50%`;
  return [
    { src: left, animate: 'animate-flap-left', origin },
    { src: right, animate: 'animate-flap-right', origin },
    { src: body },
  ];
}

